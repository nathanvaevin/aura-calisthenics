/**
 * Writes supabase/seed.sql from the catalog in src/domain, so the database and
 * the app can never disagree about exercises, ladders, skills or calibration.
 * Run: npm run db:seed
 */
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { DISCIPLINES, EXERCISES, PROGRESSIONS } from '../src/domain/catalog'
import { SKILL_DEFS } from '../src/domain/catalog/skills'
import { AURA_CLASSES, BANDS, SCORING } from '../src/domain/scoring/config'
import { WORKOUT_TEMPLATES } from '../src/domain/training'

const q = (s: string | number | boolean | null | undefined) =>
  s === null || s === undefined ? 'null' : typeof s === 'string' ? `'${s.replace(/'/g, "''")}'` : String(s)
const arr = (a: readonly string[]) => (a.length ? `array[${a.map(q).join(', ')}]` : `'{}'`)

function upsert(table: string, keys: string[], rows: Record<string, string>[]) {
  if (rows.length === 0) return ''
  const cols = Object.keys(rows[0])
  const updates = cols.filter((c) => !keys.includes(c)).map((c) => `${c} = excluded.${c}`)
  return (
    `insert into public.${table} (${cols.join(', ')}) values\n` +
    rows.map((r) => `  (${cols.map((c) => r[c]).join(', ')})`).join(',\n') +
    `\non conflict (${keys.join(', ')}) do ${updates.length ? `update set ${updates.join(', ')}` : 'nothing'};\n`
  )
}

const out: string[] = [
  '-- Generated by scripts/generate-seed.ts. Do not edit by hand.',
  `-- Scoring model ${SCORING.version}: provisional calibration, not a validated standard.`,
  'begin;',
]

out.push(upsert('disciplines', ['id'], DISCIPLINES.map((d, i) => ({ id: q(d.id), name: q(d.name), short: q(d.short), blurb: q(d.blurb), archetype: q(d.archetype), position: q(i) }))))

out.push(
  upsert('exercises', ['id'], EXERCISES.map((e) => ({
    id: q(e.id), discipline_id: q(e.discipline), name: q(e.name), short: q(e.short), category: q(e.category), metric: q(e.metric),
    per_side: q(e.perSide), equipment: arr(e.equipment), primary_muscles: arr(e.primary), secondary_muscles: arr(e.secondary),
    stabilizers: arr(e.stabilizers), summary: q(e.summary), cues: arr(e.cues), mistakes: arr(e.mistakes), safety: q(e.safety),
    standard: q(e.standard), dose_sets: q(e.dose.sets), dose_min: q(e.dose.range[0]), dose_max: q(e.dose.range[1]), dose_rest: q(e.dose.rest),
  }))),
)

out.push(upsert('progressions', ['id'], PROGRESSIONS.map((p) => ({ id: q(p.id), discipline_id: q(p.discipline), name: q(p.name), objective: q(p.objective) }))))
out.push('delete from public.progression_steps where progression_id in (select id from public.progressions where created_by is null);')
out.push(
  upsert('progression_steps', ['progression_id', 'level', 'exercise_id'], PROGRESSIONS.flatMap((p) =>
    p.steps.flatMap((s) => [
      { progression_id: q(p.id), level: q(s.level), exercise_id: q(s.exerciseId), is_alternate: 'false' },
      ...(s.alternates ?? []).map((a) => ({ progression_id: q(p.id), level: q(s.level), exercise_id: q(a), is_alternate: 'true' })),
    ]),
  )),
)

out.push(upsert('skills', ['id'], SKILL_DEFS.map((s) => ({ id: q(s.id), exercise_id: q(s.exerciseId), threshold: q(s.threshold), lane: q(s.lane), name: q(s.name) }))))
out.push('delete from public.skill_prerequisites;')
out.push(upsert('skill_prerequisites', ['skill_id', 'requires_id'], SKILL_DEFS.flatMap((s) => s.requires.map((r) => ({ skill_id: q(s.id), requires_id: q(r) })))))

const config = JSON.stringify({ ...SCORING, bands: BANDS, auraClasses: AURA_CLASSES })
out.push('update public.scoring_models set is_active = false where is_active;')
out.push(
  upsert('scoring_models', ['version'], [{
    version: q(SCORING.version), config: `${q(config)}::jsonb`, is_active: 'true',
    note: q('Provisional. A coach’s ordering of benchmarks onto one scale; to be recalibrated against athlete data.'),
  }]),
)
out.push(`delete from public.rating_curves where model_version = ${q(SCORING.version)};`)
out.push(
  upsert('rating_curves', ['model_version', 'exercise_id', 'value'], EXERCISES.flatMap((e) =>
    (e.curve ?? []).map(([value, rating]) => ({ model_version: q(SCORING.version), exercise_id: q(e.id), value: q(value), rating: q(rating) })),
  )),
)

out.push(upsert('workouts', ['id'], WORKOUT_TEMPLATES.map((w) => ({ id: q(w.id), title: q(w.title), focus: q(w.focus), summary: q(w.summary), minutes: q(w.minutes) }))))
out.push('delete from public.workout_items where workout_id in (select id from public.workouts where created_by is null);')
out.push(
  upsert('workout_items', ['workout_id', 'position'], WORKOUT_TEMPLATES.flatMap((w) =>
    w.plan.map((item, i) => ({
      workout_id: q(w.id), position: q(i), kind: q(item.kind),
      progression_id: q('progressionId' in item ? item.progressionId : null),
      exercise_id: q('exerciseId' in item ? item.exerciseId : null),
      sets: q(item.sets ?? null), target: q('target' in item ? (item.target ?? null) : null),
    })),
  )),
)

out.push('commit;', '')

const file = fileURLToPath(new URL('../supabase/seed.sql', import.meta.url))
writeFileSync(file, out.join('\n'))
console.log(`Wrote ${file}`)
console.log(`  ${DISCIPLINES.length} disciplines, ${EXERCISES.length} exercises, ${PROGRESSIONS.length} progressions, ${SKILL_DEFS.length} skills, ${WORKOUT_TEMPLATES.length} workouts`)
