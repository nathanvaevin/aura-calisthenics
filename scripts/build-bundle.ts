/**
 * Builds supabase/apply.sql: every migration in order, then the seed, in one
 * file you can paste into the Supabase SQL editor once on a fresh project.
 *
 *   npm run db:bundle
 *
 * Regenerate it whenever a migration or the seed changes. `npm run db:check`
 * proves the same SQL applies to an in-process Postgres; this only concatenates
 * it for convenience. The migrations are not wrapped in one transaction on
 * purpose: they are applied statement by statement, exactly as the Supabase CLI
 * would apply them, and the seed carries its own transaction.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const rel = (p: string) => fileURLToPath(new URL(p, import.meta.url))
const read = (p: string) => readFileSync(rel(p), 'utf8').trim()

const MIGRATIONS = ['0001_core.sql', '0002_storage.sql', '0003_evidence_observed.sql', '0004_assessments.sql', '0005_places.sql', '0006_live.sql', '0007_coach_access.sql', '0008_course_weeks_and_station_mode.sql', '0009_visual_content.sql', '0010_start_over.sql', '0011_personal_style.sql', '0012_ratings_open.sql', '0013_more_themes.sql', '0014_coach_sees_training.sql', '0015_block_name_and_unit.sql', '0016_block_complete.sql']

const header = `-- Aura · complete database setup
-- Generated by scripts/build-bundle.ts — do not edit by hand (run: npm run db:bundle).
--
-- Paste this whole file into the Supabase SQL editor of a FRESH project and run it
-- once. It creates the schema, the access rules and the catalog + demo data.
-- See supabase/README.md for the full setup, including Google sign-in.
--
-- Contents: ${MIGRATIONS.join(', ')}, then seed.sql.
`

const section = (title: string, body: string) =>
  `\n-- ${'═'.repeat(72)}\n-- ${title}\n-- ${'═'.repeat(72)}\n\n${body}\n`

const parts = [
  header,
  ...MIGRATIONS.map((f) => section(f, read(`../supabase/migrations/${f}`))),
  section('seed.sql — catalog and demo data', read('../supabase/seed.sql')),
]

writeFileSync(rel('../supabase/apply.sql'), parts.join('\n') + '\n')
console.log(`Wrote supabase/apply.sql (${MIGRATIONS.length} migrations + seed).`)
